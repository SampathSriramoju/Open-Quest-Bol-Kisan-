    random.shuffle(items)
    n = len(items)
    n_val = max(1, int(round(n * 0.15)))
    n_holdout = max(1, int(round(n * 0.15)))
    n_dev = n - n_val - n_holdout

    # Edge case adjustments
    if n_dev < 0:
        n_dev = n - 2
        n_val = 1
        n_holdout = 1

    dev_set.extend(items[:n_dev])
    val_set.extend(items[n_dev:n_dev + n_val])
    holdout_set.extend(items[n_dev + n_val:])

